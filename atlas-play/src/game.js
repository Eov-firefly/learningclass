export function localDate(date = new Date()) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}
export function distanceKm(a, b) {
  const rad = Math.PI / 180;
  const dl = (b.lat - a.lat) * rad,
    dn = (b.lng - a.lng) * rad;
  const h =
    Math.sin(dl / 2) ** 2 +
    Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dn / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.sqrt(Math.min(1, Math.max(0, h))));
}
// Original smooth curve: full marks within 22km; falls continuously to zero at the antipode.
export function scoreDistance(km) {
  return Math.round(100 * Math.max(0, 1 - Math.max(0, km - 22) / 19993) ** 2);
}
export function selectPlaces(seed, category = "all") {
  let n = 2166136261;
  for (const c of seed) n = Math.imul(n ^ c.charCodeAt(0), 16777619) >>> 0;
  const a = PLACES.filter((p) => category === "all" || p.category === category);
  for (let i = a.length - 1; i > 0; i--) {
    n = (Math.imul(n, 1664525) + 1013904223) >>> 0;
    const j = n % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a.slice(0, 5);
}
export function totalScore(rounds) {
  return rounds.reduce((s, r, i) => s + r.score * WEIGHTS[i], 0);
}
export function validSave(s, date) {
  return (
    s?.date === date &&
    Array.isArray(s.places) &&
    s.places.length === 5 &&
    s.places.every((id) => Number.isInteger(id) && PLACES[id]) &&
    Array.isArray(s.rounds) &&
    s.rounds.length <= 5 &&
    s.rounds.every(
      (r, i) =>
        Number.isInteger(r.score) &&
        r.score >= 0 &&
        r.score <= 100 &&
        Number.isFinite(r.distance) &&
        r.distance >= 0 &&
        r.placeId === s.places[i] &&
        Number.isFinite(r.guess?.lat) &&
        Math.abs(r.guess.lat) <= 90 &&
        Number.isFinite(r.guess?.lng) &&
        Math.abs(r.guess.lng) <= 180,
    )
  );
}
export function streak(history, date = localDate()) {
  let cursor = new Date(`${date}T12:00:00`),
    count = 0;
  if (!history[localDate(cursor)]) cursor.setDate(cursor.getDate() - 1);
  while (history[localDate(cursor)]) {
    count++;
    cursor.setDate(cursor.getDate() - 1);
  }
  return count;
}
